import { RoutineConfig, TierChain } from '../types';

function prescription(
  sets: number,
  minReps: number,
  maxReps: number,
  restLabel: string,
  cue: string,
  targetRir = '1-2 RIR',
  finalSetRir?: string,
): NonNullable<TierChain['prescription']> {
  const restSeconds = restLabel.includes('3 min')
    ? 180
    : restLabel.includes('2.5')
      ? 150
      : restLabel.includes('2 min')
        ? 120
        : restLabel.includes('75')
          ? 75
          : restLabel.includes('60')
            ? 60
            : 90;
  const [targetRirMin, targetRirMax] = targetRir.includes('0-1')
    ? [0, 1]
    : targetRir.includes('1-2')
      ? [1, 2]
      : targetRir.includes('2')
        ? [2, 2]
        : [1, 1];

  return {
    sets,
    minReps,
    maxReps,
    targetRir,
    targetRirMin,
    targetRirMax,
    finalSetRir,
    restSeconds,
    restLabel,
    cue,
  };
}

