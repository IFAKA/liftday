import { RoutineConfig, TierChain } from '../types';

function prescription(
  sets: number,
  minReps: number,
  maxReps: number,
  restLabel: string,
  cue: string,
  finalSetRir?: string,
): NonNullable<TierChain['prescription']> {
  const restSeconds = restLabel.includes('3 min') ? 180 : restLabel.includes('2.5') ? 150 : restLabel.includes('120') ? 120 : 90;
  return {
    sets,
    minReps,
    maxReps,
    targetRir: '1-2 RIR',
    targetRirMin: 1,
    targetRirMax: 2,
    finalSetRir,
    restSeconds,
    restLabel,
    cue,
  };
}

